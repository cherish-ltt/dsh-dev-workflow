/**
 * 需求确认提示词：优先使用 prompt-check，内置文本仅作不可用时的保底。
 */

export const DEV_ASK_TOOL_NAME = "dev_ask";

export const READ_ONLY_EXPLORATION_RULES = [
	"- 用 read / grep / glob 等只读工具确认：入口文件、现有实现、相关测试、项目约定与配置。",
	"- 不臆测文件路径、接口签名、依赖与既有行为。",
	"- 相关概念在代码库中确实不存在时，明确写出「未发现」并交代检索范围（搜了什么、覆盖哪些目录）。",
	"- 探查到足以支撑产出为止，不做与任务无关的全库通读。",
];

const RESTATE_INSTRUCTION = [
	"## 内置 Prompt Check",
	"准确理解原始需求，结合真实项目形成可验证的需求理解；区分明确要求、合理推断和未知信息。",
	"",
	"### 先探索项目，再形成理解",
	"分析任务类型、用户目标、范围、约束、交付物与验收标准，再探索相关真实上下文。",
	...READ_ONLY_EXPLORATION_RULES,
	"- 检查 README、AGENTS.md、相关调用关系、测试约定及 Git 当前状态和未提交变更。",
	"- 不读取无关敏感配置、密钥和凭证；无法访问的上下文明确标记为未核实。",
	"",
	"### 关键不确定项",
	"- 先完成已授权的只读探索，只询问可能改变行为、接口、数据、安全、范围或验收结果的问题。",
	"- 能从代码、文档或原始需求确定的内容不提问；低风险假设必要时明确标注。",
	"- 每题包含问题、2-4 个真实可行选项和简洁说明，推荐项在前，允许自定义回答；尽可能一次问完。",
	"- 不为完整性制造问题；涉及不可逆操作、外部写入或重大范围变更时明确授权边界。",
	"",
	"### 输出需求理解报告（严格使用以下结构）",
	"## 已核实的项目现状",
	"用表格列出相关文件、实际发现与需求的关系，附真实路径和必要位置；仅列相关证据，未知内容标记未核实。",
	"",
	"## 重新复述用户 Prompt",
	"用自己的话准确保留用户意图，消除歧义和重复，不增加功能，不输出内部推理。",
	"",
	"## 试图解决的问题与用户目标",
	"用表格明确使用对象、目标、范围、约束和验收标准，区分明确要求与基于项目的推断。",
	"",
	"## 不确定之处",
	"列出仍需用户决策的问题与原因；没有则写：目前没有影响执行方向的关键不确定项。",
	"",
	"## 一句话概括",
	"30 字以内概括确认后准备执行的任务。",
].join("\n");

export function buildPreCheckPrompt(originalPrompt, corrections, guidance = {}) {
	const parts = [
		"[pre-check] 任务意图校验：只复述，不执行",
		"",
		"## 用户原始 prompt（原文）",
		originalPrompt,
		"",
		...(guidance.warning ? [guidance.warning, "请在报告开头向用户说明上述降级原因。", ""] : []),
		guidance.instruction ?? RESTATE_INSTRUCTION,
		"",
		"## 本次命令的确认边界",
		"- 当前仅执行需求理解阶段；用户选择了先确认的 dev 命令，原始任务文本不代表已通过本次确认。",
		"- 确认前严格只读：禁止文件写入、依赖安装、构建、测试、Git 写操作及任何写入类工具。",
		"- 不输出代码、补丁或具体实施方案。",
		`- 关键澄清优先使用实际可用的 ${DEV_ASK_TOOL_NAME}；没有提问工具时将待决问题写入报告，不臆造工具。`,
		"- 报告完成后立即停止。最终确认由命令提供交互卡，不要自行调用工具重复请求确认或提前执行。",
	];

	if (corrections.length > 0) {
		parts.push(
			"",
			"## 用户对上一次复述的修正（必须吸收）",
			...corrections.map((correction, index) => `${index + 1}. ${correction}`),
		);
	}

	return parts.join("\n");
}

export function buildExecutionPrompt(originalPrompt, intent) {
	return [
		"[execute] 意图已确认，开始执行",
		"",
		"## 用户原始 prompt（原文，权威需求）",
		originalPrompt,
		"",
		"## 已由用户确认的任务意图",
		intent,
		"",
		"## 要求",
		"- 现在开始执行用户原始 prompt 描述的工作。",
		"- 以上已确认意图是本任务的权威前提；与你的理解冲突时，以该意图为准。",
		"- 意图已确认；按原始任务类型和授权范围自主执行，不重复要求确认常规可逆操作或实施计划。",
		"- 仅遇到新的重大不确定项、破坏性操作、未授权外部写入或范围变化时提问。",
		"- 根据实际改动验证，报告真实完成内容、测试结果及未解决问题，不把预期当成已完成。",
	].join("\n");
}
